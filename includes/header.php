    <script>
    (function() {
      function initResponsiveNav() {
        var burger = document.getElementById('cp-burger');
        var menu = document.getElementById('cp-links');
        if (!burger || !menu) return;

        function toggleMenu(e) {
          if (e) {
            e.preventDefault();
            e.stopPropagation();
          }
          var isOpen = menu.classList.toggle('is-open');
          menu.classList.toggle('open', isOpen);
          burger.classList.toggle('is-active', isOpen);
          burger.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
        }

        function closeMenu() {
          if (menu.classList.contains('is-open') || menu.classList.contains('open')) {
            menu.classList.remove('is-open', 'open');
            burger.classList.remove('is-active');
            burger.setAttribute('aria-expanded', 'false');
          }
        }

        burger.addEventListener('click', toggleMenu);

        document.addEventListener('click', function(e) {
          if (!menu.contains(e.target) && !burger.contains(e.target)) {
            closeMenu();
          }
        });

        document.addEventListener('keydown', function(e) {
          if (e.key === 'Escape') closeMenu();
        });

        menu.querySelectorAll('.cp-nav__link').forEach(function(link) {
          link.addEventListener('click', function() {
            closeMenu();
          });
        });
      }

      if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initResponsiveNav);
      } else {
        initResponsiveNav();
      }
    })();
    </script>
